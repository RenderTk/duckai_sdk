"""Copy the shared model snapshot into independently distributable SDK packages."""

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    models = json.loads((ROOT / "protocol/models.json").read_text())
    constants = {m["constant"]: m["id"] for m in models}
    python = ROOT / "sdks/python/duckai/catalog.py"
    source = python.read_text()
    tree = ast.parse(source)
    enum = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Model")
    lines = source.splitlines(keepends=True)
    replacement = "class Model(StrEnum):\n" + "".join(
        f"    {name} = {json.dumps(value)}\n" for name, value in constants.items()
    )
    source = "".join(lines[: enum.lineno - 1]) + replacement + "".join(lines[enum.end_lineno :])
    data = json.dumps(models, indent=2) + "\n"
    ts = "// Generated by scripts/sync_protocol.py. Edit protocol/models.json.\n"
    ts += "export const Model = " + json.dumps(constants, indent=2) + " as const;\n"
    outputs = {
        python: source,
        ROOT / "sdks/python/duckai/_catalog_data.json": data,
        ROOT / "sdks/typescript/src/catalog-data.json": data,
        ROOT / "sdks/typescript/src/model-constants.ts": ts,
        ROOT / "sdks/python/docs/file-formats.md": (ROOT / "docs/file-formats.md").read_text(),
    }
    swift_constants = "// Generated by scripts/sync_protocol.py.\npublic enum Model {\n"
    dart_constants = "// Generated by scripts/sync_protocol.py.\nabstract final class Model {\n"
    cs_constants = (
        "// Generated by scripts/sync_protocol.py.\n"
        "namespace DuckAI;\npublic static class Model {\n"
    )
    for name, value in constants.items():
        parts = name.lower().split("_")
        camel = parts[0] + "".join(part.capitalize() for part in parts[1:])
        swift_constants += f"    public static let {camel} = {json.dumps(value)}\n"
        dart_constants += f"  static const {camel} = {json.dumps(value)};\n"
        cs_constants += f"    public const string {name} = {json.dumps(value)};\n"
    outputs[ROOT / "sdks/swift/Sources/DuckAI/Model.swift"] = swift_constants + "}\n"
    outputs[ROOT / "sdks/dart/lib/src/model.dart"] = dart_constants + "}\n"
    outputs[ROOT / "sdks/csharp/DuckAI/Model.cs"] = cs_constants + "}\n"
    for directory in [
        "sdks/swift/Sources/DuckAI/Resources",
        "sdks/dart/assets",
        "sdks/csharp/DuckAI/Resources",
    ]:
        outputs[ROOT / directory / "models.json"] = data
        outputs[ROOT / directory / "browser-bootstrap.js"] = (
            ROOT / "protocol/browser-bootstrap.js"
        ).read_text()
    for directory in ["sdks/swift/Sources/DuckAI/Resources", "sdks/dart/assets"]:
        outputs[ROOT / directory / "browser-transport.js"] = (
            ROOT / "protocol/browser-transport.js"
        ).read_text()
    for name in ["chat.json", "documents.json", "images.json", "pdfs.json"]:
        outputs[ROOT / "sdks/swift/Tests/DuckAITests/Fixtures" / name] = (
            ROOT / "protocol/fixtures" / name
        ).read_text()
    smoke = json.loads((ROOT / "protocol/fixtures/images.json").read_text())
    smoke += json.loads((ROOT / "protocol/fixtures/pdfs.json").read_text())
    for destination in ["sdks/swift/Examples/App", "sdks/dart/example/assets"]:
        outputs[ROOT / destination / "smoke-files.json"] = json.dumps(smoke, indent=2) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if mismatches:
        raise SystemExit(
            "Run python scripts/sync_protocol.py; stale files: " + ", ".join(mismatches)
        )


if __name__ == "__main__":
    main()
